#!/bin/sh
# REPO-INS-002 — no AI-authorship attribution in commit metadata (across the
# review range) or in the pull-request body when the GitHub event provides it.
# Range excludes the synthetic PR merge commit (via _range.sh) but still inspects
# developer-created merges. Fails closed if git cannot read the range.
set -eu
. "$(dirname "$0")/_range.sh"
pattern='generated with|generated by[[:space:]]*(claude|anthropic|chatgpt|openai|copilot|gpt)|ai[- ]generated|claude code|co-authored-by:[[:space:]]*(claude|anthropic|chatgpt|openai|copilot)|🤖'

if ! log=$(git log "$LATTICE_LOG_RANGE" --format='%H %an <%ae>%n%s%n%b' 2>&1); then
  echo "error: cannot inspect range $LATTICE_LOG_RANGE:"
  echo "$log"
  exit 1
fi
hits=$(printf '%s\n' "$log" | grep -iE "$pattern" || true)

# Also inspect the PR body in a pull_request GitHub event.
if [ -n "${GITHUB_EVENT_PATH:-}" ] && [ -f "$GITHUB_EVENT_PATH" ]; then
  body=$(python3 -c "import json,os; d=json.load(open(os.environ['GITHUB_EVENT_PATH'])); print((d.get('pull_request') or {}).get('body') or '')" 2>/dev/null || true)
  body_hits=$(printf '%s\n' "$body" | grep -iE "$pattern" || true)
  [ -n "$body_hits" ] && hits="$hits
[PR body] $body_hits"
fi

if [ -n "$(printf '%s' "$hits" | tr -d '[:space:]')" ]; then
  echo "AI-attribution markers found:"
  echo "$hits"
  exit 1
fi
echo "No AI-attribution markers in $LATTICE_LOG_RANGE (and PR body if present)."
