#!/usr/bin/env python3
"""Lattice check installer / materializer (SPEC §5.2–§5.4).

Reads the packs, applies freshness verification for *this* recipient, and
writes the deterministic enforcement artifacts as idempotent managed blocks:

- GATE  checks -> ``.github/workflows/lattice-checks.yaml`` (pre-merge CI).
- DEEP  checks -> ``.github/workflows/lattice-deep.yaml`` (scheduled job).
- INNER checks -> two targets, because a tier is a *budget class*, not a single
  install location: a lattice-managed PostToolUse hook in
  ``.claude/settings.json`` (agent harness) **and** a ``.git/hooks/pre-commit``
  hook (humans editing outside the agent). Both call the same runner.

Rendering is deterministic: identical lattice version -> byte-identical output.
That property is what makes ``--verify`` possible: it re-renders in memory and
diffs against what is committed, so a pack edit that was never materialized
fails CI instead of silently leaving stale enforcement in place.

Usage:
    install_checks.py            # materialize (writes artifacts)
    install_checks.py --verify   # drift check only; writes nothing, exit 1 on drift
"""

from __future__ import annotations

import argparse
import json
import stat
import sys
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parent))

from _common import (  # noqa: E402
    REPO_ROOT,
    installable_checks,
    lattice_version_hash,
    load_version,
)

GATE_WORKFLOW = REPO_ROOT / ".github" / "workflows" / "lattice-checks.yaml"
DEEP_WORKFLOW = REPO_ROOT / ".github" / "workflows" / "lattice-deep.yaml"
SETTINGS_PATH = REPO_ROOT / ".claude" / "settings.json"
PRECOMMIT_PATH = REPO_ROOT / ".git" / "hooks" / "pre-commit"

RUNNER = ".lattice/bin/run_check.py"
PY = "uv run --with pyyaml python"
INNER_SENTINEL = f"{RUNNER} --tier inner"
GENERATED_MARK = "GENERATED BY .lattice/bin/install_checks.py"


def _group_by_command(checks: list[dict[str, Any]]) -> list[tuple[str, list[dict[str, Any]]]]:
    """Group checks by shared command, ordered by first rule id (deterministic)."""
    grouped: dict[str, list[dict[str, Any]]] = {}
    for check in sorted(checks, key=lambda c: c["id"]):
        grouped.setdefault(check["check_command"], []).append(check)
    return sorted(grouped.items(), key=lambda kv: kv[1][0]["id"])


def _check_steps(checks: list[dict[str, Any]], tier_label: str, event: str) -> list[str]:
    """Render one CI step per unique command. warn-only steps never block.

    Step names embed the check_command verbatim (e.g. ``RUSTDOCFLAGS="-D warnings"``),
    so the name is rendered with ``json.dumps`` — a JSON string is a valid YAML
    double-quoted scalar and escapes quotes/backslashes/control chars correctly.
    """
    lines: list[str] = []
    for command, group in _group_by_command(checks):
        ids = " ".join(c["id"] for c in group)
        name = json.dumps(f"{tier_label} {ids} — {command}", ensure_ascii=False)
        lines.append(f"      - name: {name}")
        if all(c.get("state") == "warn-only" for c in group):
            lines.append("        continue-on-error: true  # warn-only")
        lines.append(f"        run: {PY} {RUNNER} {ids} --event {event}")
    return lines


def _header(version: str, vhash: str, tier_note: str) -> list[str]:
    return [
        f"# {GENERATED_MARK} — DO NOT EDIT.",
        f"# Lattice version: {version} ({vhash}). Re-run the installer to update.",
        f"# {tier_note}",
    ]


def _needs_rust(checks: list[dict[str, Any]]) -> bool:
    """True if any check shells out to cargo (needs a toolchain on the runner)."""
    return any("cargo " in (c.get("check_command") or "") for c in checks)


def _setup_steps(checks: list[dict[str, Any]] | None = None) -> list[str]:
    steps = [
        "      - uses: actions/checkout@v4",
        "        with:",
        # Full history so the git-range checks can resolve origin/main..HEAD.
        "          fetch-depth: 0",
        "          persist-credentials: false",
        "      - name: Install uv",
        "        uses: astral-sh/setup-uv@v6",
        "        with:",
        '          python-version: "3.11"',
        "      - name: Install dependencies",
        "        run: uv sync --extra dev",
    ]
    if checks and _needs_rust(checks):
        # Rust checks (clippy/fmt/doc/test) need a toolchain; without this the
        # runner would report "cargo: not found" — a false failure (journal 08-21).
        steps += [
            "      - name: Install Rust toolchain",
            "        uses: dtolnay/rust-toolchain@stable",
            "        with:",
            "          components: clippy, rustfmt",
        ]
    return steps


def _trace_upload_steps() -> list[str]:
    return [
        "      - name: Upload T2 traces",
        "        if: always()",
        "        uses: actions/upload-artifact@v4",
        "        with:",
        "          name: lattice-t2-traces",
        "          path: .lattice/traces/T2/",
        "          if-no-files-found: ignore",
        "",
    ]


def _render_gate_workflow(gate: list[dict[str, Any]], version: str, vhash: str) -> str:
    """GATE tier -> pre-merge CI (SPEC §5.3)."""
    lines = _header(
        version,
        vhash,
        "GATE-tier checks: pre-merge CI. warn-only steps never block; promotion to\n"
        "# enforced (blocking) happens through the improvement loop on T2 evidence.",
    ) + [
        "name: Lattice Checks",
        "",
        "on:",
        "  push:",
        '    branches: [main, "release-**"]',
        "  pull_request:",
        '    branches: [main, "release-**"]',
        "",
        "permissions:",
        "  contents: read",
        "",
        "jobs:",
        "  lattice-gate:",
        "    runs-on: ubuntu-latest",
        "    steps:",
    ]
    lines += _setup_steps(gate)
    lines += _check_steps(gate, "GATE", "ci")
    lines += _trace_upload_steps()
    return "\n".join(lines)


def _render_deep_workflow(deep: list[dict[str, Any]], version: str, vhash: str) -> str:
    """DEEP tier -> scheduled job (SPEC §5.3).

    Deep checks are uncapped and off the merge path entirely: their job is to
    accumulate T2 evidence over time (coverage trend, dependency advisories),
    which is what the improvement loop later reads to justify promotion.
    """
    lines = _header(
        version,
        vhash,
        "DEEP-tier checks: scheduled job, off the merge path. Failures are surfaced\n"
        "# for the next improvement-loop pass, never blocking a merge.",
    ) + [
        "name: Lattice Deep Checks",
        "",
        "on:",
        "  schedule:",
        '    - cron: "0 6 * * 1"  # Mondays 06:00 UTC',
        "  workflow_dispatch:",
        "",
        "permissions:",
        "  contents: read",
        "",
        "jobs:",
        "  lattice-deep:",
        "    runs-on: ubuntu-latest",
        "    steps:",
    ]
    lines += _setup_steps(deep)
    lines += _check_steps(deep, "DEEP", "scheduled")
    lines += _trace_upload_steps()
    return "\n".join(lines)


def _render_precommit(inner: list[dict[str, Any]], version: str, vhash: str) -> str:
    """INNER tier -> git pre-commit hook.

    The PostToolUse hook only fires inside an agent session. This is the same
    check set for a human editing in any editor, so enforcement does not depend
    on *who* made the change.
    """
    ids = " ".join(c["id"] for c in sorted(inner, key=lambda c: c["id"]))
    return "\n".join(
        [
            "#!/bin/sh",
            f"# {GENERATED_MARK} — DO NOT EDIT.",
            f"# Lattice version: {version} ({vhash}).",
            f"# INNER-tier checks at commit time: {ids}",
            "# warn-only checks always exit 0; this never blocks a commit today.",
            f"exec {PY} {RUNNER} --tier inner --event precommit",
            "",
        ]
    )


def _expected_workflows(
    by_tier: dict[str, list[dict[str, Any]]], version: str, vhash: str
) -> dict[Path, str | None]:
    """Tracked generated artifacts -> expected content (None = must not exist).

    Only tracked files are drift-verified. ``.git/hooks/pre-commit`` is per-clone
    and absent in CI, so it is installed but never verified.
    """
    return {
        GATE_WORKFLOW: (
            _render_gate_workflow(by_tier["gate"], version, vhash) if by_tier["gate"] else None
        ),
        DEEP_WORKFLOW: (
            _render_deep_workflow(by_tier["deep"], version, vhash) if by_tier["deep"] else None
        ),
    }


def _expected_hook_command() -> str:
    return f"{PY} {RUNNER} --tier inner --event posttooluse"


def _install_inner_hook(inner: list[dict[str, Any]]) -> str:
    """Insert/refresh the lattice PostToolUse hook in settings.json. Idempotent."""
    settings: dict[str, Any] = {}
    if SETTINGS_PATH.exists():
        settings = json.loads(SETTINGS_PATH.read_text())

    hooks = settings.setdefault("hooks", {})
    post = hooks.setdefault("PostToolUse", [])
    # Drop any prior lattice-managed entry (sentinel match), then re-add fresh.
    post = [e for e in post if INNER_SENTINEL not in json.dumps(e)]

    if inner:
        post.append(
            {
                "matcher": "Edit|Write|MultiEdit",
                "hooks": [{"type": "command", "command": _expected_hook_command()}],
            }
        )
    hooks["PostToolUse"] = post
    if not post:
        hooks.pop("PostToolUse", None)
    if not hooks:
        settings.pop("hooks", None)

    SETTINGS_PATH.write_text(json.dumps(settings, indent=2) + "\n")
    return ", ".join(c["id"] for c in inner) if inner else "(none)"


def _settings_hook_ok() -> bool:
    """True when settings.json carries exactly the expected managed hook entry."""
    if not SETTINGS_PATH.exists():
        return False
    try:
        settings = json.loads(SETTINGS_PATH.read_text())
    except json.JSONDecodeError:
        return False
    entries = settings.get("hooks", {}).get("PostToolUse", [])
    managed = [e for e in entries if INNER_SENTINEL in json.dumps(e)]
    if len(managed) != 1:
        return False
    commands = [h.get("command") for h in managed[0].get("hooks", [])]
    return commands == [_expected_hook_command()]


def _install_precommit(inner: list[dict[str, Any]], version: str, vhash: str) -> str:
    """Write .git/hooks/pre-commit, refusing to clobber a foreign hook."""
    if not PRECOMMIT_PATH.parent.exists():
        return "skipped (no .git/hooks directory)"
    if not inner:
        return "skipped (no inner-tier checks)"
    if PRECOMMIT_PATH.exists() and GENERATED_MARK not in PRECOMMIT_PATH.read_text():
        return "SKIPPED — a non-lattice pre-commit hook already exists; merge manually"

    PRECOMMIT_PATH.write_text(_render_precommit(inner, version, vhash))
    PRECOMMIT_PATH.chmod(PRECOMMIT_PATH.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP)
    return "installed"


def _verify(by_tier: dict[str, list[dict[str, Any]]], version: str, vhash: str) -> int:
    """Diff committed artifacts against a fresh in-memory render (CORE-CHK-001)."""
    drifted: list[str] = []
    for path, expected in _expected_workflows(by_tier, version, vhash).items():
        rel = path.relative_to(REPO_ROOT)
        actual = path.read_text() if path.exists() else None
        if actual == expected:
            print(f"[ok]    {rel}")
        elif expected is None:
            drifted.append(f"{rel}: present but no checks of that tier are installable")
        elif actual is None:
            drifted.append(f"{rel}: missing — installer was never run")
        else:
            drifted.append(f"{rel}: content differs from the packs")

    if _settings_hook_ok():
        print(f"[ok]    {SETTINGS_PATH.relative_to(REPO_ROOT)} (managed PostToolUse entry)")
    elif by_tier["inner"]:
        drifted.append(
            f"{SETTINGS_PATH.relative_to(REPO_ROOT)}: managed PostToolUse entry missing or stale"
        )

    if drifted:
        print(f"\nDRIFT — {len(drifted)} artifact(s) out of sync with .lattice/packs/:")
        for item in drifted:
            print(f"        · {item}")
        print("\nFix: uv run --with pyyaml python .lattice/bin/install_checks.py")
        return 1

    print(f"\nAll generated artifacts match lattice {version} ({vhash}).")
    return 0


def _assert_valid_yaml(content: str, path: Path) -> None:
    """Fail loudly if a rendered workflow is not parseable YAML.

    A malformed workflow fails on GitHub in 0s with a useless error, so catch it
    at generation time instead. PyYAML is always present (scripts run under
    `uv run --with pyyaml`); skip the guard if somehow absent.
    """
    try:
        import yaml
    except ModuleNotFoundError:
        return
    try:
        yaml.safe_load(content)
    except yaml.YAMLError as exc:
        raise SystemExit(
            f"ERROR: generated {path.relative_to(REPO_ROOT)} is not valid YAML:\n{exc}"
        )


def _tiered(keep: list[dict[str, Any]]) -> dict[str, list[dict[str, Any]]]:
    by_tier: dict[str, list[dict[str, Any]]] = {"inner": [], "gate": [], "deep": [], "other": []}
    for check in keep:
        by_tier.get(check.get("tier"), by_tier["other"]).append(check)
    return by_tier


def _report_group(label: str, path: Path, checks: list[dict[str, Any]]) -> None:
    commands = _group_by_command(checks)
    print(
        f"{label} -> {path.relative_to(REPO_ROOT)}  "
        f"({len(checks)} checks, {len(commands)} steps after dedup)"
    )
    for command, group in commands:
        print(f"        · {' '.join(c['id'] for c in group)}: {command}")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Materialize lattice checks into enforcement.")
    parser.add_argument(
        "--verify",
        action="store_true",
        help="Check generated artifacts against the packs; write nothing (exit 1 on drift)",
    )
    args = parser.parse_args(argv)

    version = str(load_version().get("version", "unknown"))
    vhash = lattice_version_hash()
    keep, skip = installable_checks()
    by_tier = _tiered(keep)

    if args.verify:
        print(f"Lattice drift check — version {version} ({vhash})\n")
        return _verify(by_tier, version, vhash)

    print(f"Lattice check installation — version {version} ({vhash})\n")

    expected = _expected_workflows(by_tier, version, vhash)
    # Validate every workflow BEFORE writing any, so a failure never leaves a
    # partially materialized set of generated artifacts on disk.
    for path, content in expected.items():
        if content is not None:
            _assert_valid_yaml(content, path)
    for label, path, checks in (
        ("GATE ", GATE_WORKFLOW, by_tier["gate"]),
        ("DEEP ", DEEP_WORKFLOW, by_tier["deep"]),
    ):
        if checks:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected[path] or "")
            _report_group(label, path, checks)
        elif path.exists():
            path.unlink()
            print(f"{label} -> removed {path.relative_to(REPO_ROOT)} (no installable checks)")

    ids = _install_inner_hook(by_tier["inner"])
    print(f"\nINNER -> {SETTINGS_PATH.relative_to(REPO_ROOT)} PostToolUse hook  ({ids})")
    status = _install_precommit(by_tier["inner"], version, vhash)
    print(f"INNER -> .git/hooks/pre-commit  ({status})")

    if by_tier["other"]:
        print("\nUNPLACED — checks with an unrecognized tier:")
        for check in by_tier["other"]:
            print(f"        · {check['id']}: tier={check.get('tier')!r}")

    if skip:
        print(f"\nSkipped {len(skip)} check(s) — freshness (SPEC §5.4):")
        for check, reason in sorted(skip, key=lambda cr: cr[0]["id"]):
            print(f"        · {check['id']} [{check.get('_pack')}]: {reason}")

    print("\nDone.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
